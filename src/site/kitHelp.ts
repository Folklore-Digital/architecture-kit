/** Output path for the generated kit help page (site root). */
export const KIT_HELP_OUTPUT = 'help.html';

export type KitHelpOptions = {
  kitVersion: string;
};

function esc(text: string): string {
  return text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

/** Short blurb for the home page — links to full help. */
export function renderKitHelpSummary(helpHref: string): string {
  return `<section class="home-section home-section--kit">
  <h2>About this site</h2>
  <p class="home-kit-blurb">
    These pages are built from Markdown in <code>docs/</code> by
    <strong>@folklore/architecture-kit</strong> — system architecture docs for structure,
    deployment, integrations, and decisions. Feature specs and tickets stay in Monday / your
    tracker; link them from the documentation map, don&rsquo;t duplicate them here.
  </p>
  <p><a class="home-help-link" href="${esc(helpHref)}">Help — commands, validation &amp; editing docs →</a></p>
</section>`;
}

